#!/usr/bin/env python3
"""ui/i18n/de.json + en.json -> C tables (SPEC 9: no texts in C code).

    i18n_gen.py de.json en.json OUTDIR        writes OUTDIR/i18n.h and OUTDIR/i18n_de.c
    i18n_gen.py --check de.json en.json DIR   same keys and placeholders in both languages,
                                              every TX_*/TXL_* used in DIR exists, no sharp s

Strings become TX_<KEY>. Lists and objects (tables of the v1 web UI, e.g. "pins", "io.di")
are flattened to "<key>.1", "<key>.2" ... (1-based) and get an index table TXL_<KEY>
(index 0 = "<key>.1", TX_NONE for empty entries).
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path


def ident(key: str) -> str:
    return "TX_" + re.sub(r"[^A-Za-z0-9]", "_", key).upper()


def c_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def load(path: Path) -> tuple[dict[str, str], dict[str, list[str | None]]]:
    data = json.loads(path.read_text(encoding="utf-8"))
    out: dict[str, str] = {}
    tables: dict[str, list[str | None]] = {}
    for k, v in data.items():
        if "ß" in json.dumps(v, ensure_ascii=False):
            sys.exit(f"{k}: Swiss spelling, no sharp s")
        if isinstance(v, str):
            out[k] = v
        elif isinstance(v, (list, dict)):
            items = v if isinstance(v, list) else [v.get(str(i)) for i in range(1, max(map(int, v)) + 1)]
            keys: list[str | None] = []
            for i, item in enumerate(items, 1):
                if isinstance(item, str):
                    out[f"{k}.{i}"] = item
                    keys.append(f"{k}.{i}")
                else:
                    keys.append(None)
            tables[k] = keys
    return out, tables


def table_name(key: str) -> str:
    return "TXL_" + ident(key)[3:]


# Characters outside Latin-1 that tools/gen_fonts.sh puts into the fonts.
FONT_EXTRA = {0x2013, 0x2018, 0x2019, 0x201A, 0x201B, 0x201C, 0x201D, 0x201E, 0x2022, 0x2026,
              0x2039, 0x203A, 0x2192, 0x2194, 0x2212}


def glyphs(texts: dict[str, str]) -> None:
    for k, v in texts.items():
        bad = [c for c in v if ord(c) > 0xFF and ord(c) not in FONT_EXTRA]
        if bad:
            sys.exit(f"{k}: character {bad[0]!r} is not in the fonts (tools/gen_fonts.sh)")


def compare(de: dict[str, str], en: dict[str, str]) -> None:
    glyphs(de)
    glyphs(en)
    if set(de) != set(en):
        sys.exit("de.json and en.json differ: " + ", ".join(sorted(set(de) ^ set(en))))
    for k in de:
        if sorted(re.findall(r"\{\w+\}", de[k])) != sorted(re.findall(r"\{\w+\}", en[k])):
            sys.exit(f"{k}: placeholders differ between de and en")


def generate(src: Path, src_en: Path, out: Path) -> None:
    data, tables = load(src)
    en, _ = load(src_en)
    compare(data, en)
    out.mkdir(parents=True, exist_ok=True)
    names = [ident(k) for k in data]
    if len(set(names)) != len(names):
        sys.exit("two keys map to the same identifier")
    h = ["/* Generated by tools/i18n_gen.py from ui/i18n/de.json. Do not edit. */", "#pragma once", "",
         "typedef enum {"]
    h += [f"    {n}," for n in names]
    h += ["    TX_COUNT,", "} tx_t;", "", "#define TX_NONE TX_COUNT", "",
          "typedef enum { LANG_DE = 0, LANG_EN, LANG_COUNT } lang_t;", "",
          "extern const char *const cu_text_de[TX_COUNT];", "extern const char *const cu_text_en[TX_COUNT];",
          "extern const char *const *cu_text; /* current language */", "",
          "void i18n_set_lang(lang_t lang);", "lang_t i18n_lang(void);",
          'static inline const char *tr(tx_t id) { return id < TX_COUNT ? cu_text[id] : ""; }', ""]
    for k, keys in tables.items():
        h.append(f"#define {table_name(k)}_LEN {len(keys)}")
        h.append(f"extern const tx_t {table_name(k)}[{len(keys)}]; /* {k}.1 ... */")
    h.append("")
    c = ["/* Generated by tools/i18n_gen.py from ui/i18n/de.json and en.json. Do not edit. */",
         '#include "i18n.h"', "", "const char *const cu_text_de[TX_COUNT] = {"]
    c += [f"    [{n}] = {c_str(v)}," for n, v in zip(names, data.values())]
    c += ["};", "", "const char *const cu_text_en[TX_COUNT] = {"]
    c += [f"    [{ident(k)}] = {c_str(en[k])}," for k in data]
    c += ["};", "", "const char *const *cu_text = cu_text_de;", "static lang_t current = LANG_DE;", "",
          "void i18n_set_lang(lang_t lang)", "{",
          "    current = lang == LANG_EN ? LANG_EN : LANG_DE;",
          "    cu_text = current == LANG_EN ? cu_text_en : cu_text_de;", "}", "",
          "lang_t i18n_lang(void)", "{", "    return current;", "}", ""]
    for k, keys in tables.items():
        vals = ", ".join(ident(x) if x else "TX_NONE" for x in keys)
        c.append(f"const tx_t {table_name(k)}[{len(keys)}] = {{{vals}}};")
    c.append("")
    (out / "i18n.h").write_text("\n".join(h), encoding="utf-8")
    (out / "i18n_de.c").write_text("\n".join(c), encoding="utf-8")


def check(src: Path, src_en: Path, code_dir: Path) -> None:
    data, tables = load(src)
    compare(data, load(src_en)[0])
    known = {ident(k) for k in data} | {"TX_NONE", "TX_COUNT"}
    known |= {table_name(k) for k in tables} | {table_name(k) + "_LEN" for k in tables}
    used: set[str] = set()
    for f in sorted(code_dir.rglob("*.[ch]")):
        used |= set(re.findall(r"\bTXL?_[A-Z0-9_]+\b", f.read_text(encoding="utf-8")))
    missing = sorted(used - known)
    if missing:
        sys.exit("missing in de.json: " + ", ".join(missing))
    print(f"{len(used)} texts used, all present")


if __name__ == "__main__":
    if len(sys.argv) == 5 and sys.argv[1] == "--check":
        check(Path(sys.argv[2]), Path(sys.argv[3]), Path(sys.argv[4]))
    elif len(sys.argv) == 4:
        generate(Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3]))
    else:
        sys.exit(__doc__)
